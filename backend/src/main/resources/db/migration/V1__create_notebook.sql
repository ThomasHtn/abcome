-- Words Côme says; the normalized label (lower case, no accents) is what makes two words the same.
CREATE TABLE word (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  label VARCHAR(40) NOT NULL,
  normalized_label VARCHAR(80) NOT NULL,
  category VARCHAR(20) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_word_normalized_label UNIQUE (normalized_label),
  CONSTRAINT ck_word_category CHECK (category IN (
    'sounds', 'games_routines', 'vehicles', 'animals', 'toys', 'clothing', 'outside', 'places',
    'household', 'body_parts', 'food_drink', 'furniture_rooms', 'people', 'descriptive_words',
    'action_words', 'time_words', 'helping_verbs', 'question_words', 'prepositions', 'quantifiers',
    'pronouns', 'connecting_words', 'custom'
  ))
);

-- Pronunciation stages of a word; they go with their word.
CREATE TABLE pronunciation (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL REFERENCES word (id) ON DELETE CASCADE,
  spoken VARCHAR(60) NOT NULL,
  status VARCHAR(10) NOT NULL,
  date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT ck_pronunciation_status CHECK (status IN ('learning', 'almost', 'mastered'))
);

-- Serves the foreign key and the stage order of a word (date, then id).
CREATE INDEX idx_pronunciation_word_date ON pronunciation (word_id, date, id);

-- At most one recording per stage, kept apart so word lists never read audio bytes.
CREATE TABLE recording (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pronunciation_id BIGINT NOT NULL REFERENCES pronunciation (id) ON DELETE CASCADE,
  data BYTEA NOT NULL,
  mime_type VARCHAR(20) NOT NULL,
  size_bytes INTEGER NOT NULL,
  duration_ms INTEGER NOT NULL,
  created_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT uq_recording_pronunciation UNIQUE (pronunciation_id),
  CONSTRAINT ck_recording_mime_type CHECK (mime_type IN ('audio/webm', 'audio/mp4')),
  CONSTRAINT ck_recording_duration CHECK (duration_ms BETWEEN 1 AND 15000)
);

-- Sentences Côme says, with what he meant when the family knows it.
CREATE TABLE sentence (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spoken VARCHAR(200) NOT NULL,
  meaning VARCHAR(200),
  date DATE NOT NULL,
  created_at TIMESTAMPTZ NOT NULL
);

-- Serves the sentence list, newest first.
CREATE INDEX idx_sentence_date ON sentence (date DESC, id DESC);

-- Read-only dictionary of first words (IFDC based), used for suggestions and categories.
CREATE TABLE dictionary_entry (
  label VARCHAR(40) PRIMARY KEY,
  category VARCHAR(20) NOT NULL,
  frequent BOOLEAN NOT NULL DEFAULT FALSE,
  acquisition_rank INTEGER NOT NULL,
  source VARCHAR(10) NOT NULL,
  -- Also serves the list order: earliest acquired words first.
  CONSTRAINT uq_dictionary_entry_rank UNIQUE (acquisition_rank),
  CONSTRAINT ck_dictionary_entry_source CHECK (source IN ('ifdc', 'abcome')),
  CONSTRAINT ck_dictionary_entry_category CHECK (category IN (
    'sounds', 'games_routines', 'vehicles', 'animals', 'toys', 'clothing', 'outside', 'places',
    'household', 'body_parts', 'food_drink', 'furniture_rooms', 'people', 'descriptive_words',
    'action_words', 'time_words', 'helping_verbs', 'question_words', 'prepositions', 'quantifiers',
    'pronouns', 'connecting_words'
  ))
);
